"""Create an explicit SaProt adaptation of the previously used ESM LoRA runner."""
from pathlib import Path
import hashlib, json

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent

def main():
    source = ROOT/'train_plm_lora.py'
    text = source.read_text(encoding='utf8')
    spec = json.loads((HERE/'PROTOCOL.json').read_text())
    assert hashlib.sha256(source.read_bytes()).hexdigest() == spec['source_hashes']['train_plm_lora.py']
    def change(old,new):
        nonlocal text
        assert text.count(old) == 1, old
        text = text.replace(old,new)
    change('from experiment_core import seed_all,regression_metrics,write_json',
           'import sys\nHERE=Path(__file__).resolve().parent\nROOT=HERE.parent\nsys.path.insert(0,str(ROOT))\nfrom experiment_core import seed_all,regression_metrics,write_json')
    change('base=EsmModel.from_pretrained(path,add_pooling_layer=False,local_files_only=True)',
           'base,info=EsmModel.from_pretrained(path,add_pooling_layer=False,local_files_only=True,output_loading_info=True)\n        from native_saprot import check_loaded_weights\n        check_loaded_weights(base,info)')
    change('ids=tok(d.sequence.tolist(),return_tensors="pt",padding=True)',
           'cached=np.asarray(tok[d.row_id.to_numpy()],dtype="int64")\n    assert cached.shape==(len(d),223)\n    ids={"input_ids":torch.from_numpy(cached.copy()),"attention_mask":torch.ones((len(d),223),dtype=torch.long)}')
    change('default=Path(__file__).resolve().parent)', 'default=ROOT)')
    change('f"esm2_150m_lora_seed{a.seed}"', 'f"saprot650_pred3di_lora_seed{a.seed}"')
    change('path=root/"repro_project/assets/esm2_t30_150M_UR50D"\n    tok=AutoTokenizer.from_pretrained(path,local_files_only=True)',
           'path=root/"repro_project/assets/saprot_650m_af2"\n    cache=root/"artifacts/embeddings"\n    spec=json.loads((HERE/"PROTOCOL.json").read_text())\n    import hashlib\n    state=json.loads((cache/"saprot650_pred3di_state.json").read_text())\n    assert state["completed_rows"]==state["rows"]==31480\n    assert state["protocol_sha256"]==hashlib.sha256((HERE/"PROTOCOL.json").read_bytes()).hexdigest()\n    assert a.rank==spec["lora"]["rank"] and a.lr==spec["lora"]["lr"]\n    assert a.batch_size*a.accumulation==spec["lora"]["effective_batch"]\n    manifest=json.loads((path/"DOWNLOAD_VERIFIED.json").read_text())\n    assert manifest["revision"]==spec["model_revision"]\n    tok=np.load(cache/"saprot650_pred3di_input_ids.npy",mmap_mode="r")')
    change('"method":"ESM2-150M + supervised LoRA"',
           '"method":"Native SaProt-650M with predicted 3Di + supervised LoRA",\n            "input_features":"native 221 AA+3Di tokens; no GLOM mutation or local branches",\n            "protocol_sha256":state["protocol_sha256"],"model_revision":spec["model_revision"]')
    change('for role in ["validation","calibration","test"]:',
           'for role in (["validation"] if a.smoke else ["validation","calibration","test"]):')
    change('"""Supervised protein-LM LoRA baseline with fixed splits and complete regression metrics."""',
           '"""Native SaProt adaptation; same optimization and head as the frozen ESM LoRA protocol.\nGenerated by build_matched_lora.py; no outcome-driven hyperparameter changes.\n"""')
    compile(text, 'train_saprot_lora.py', 'exec')
    (HERE/'train_saprot_lora.py').write_text(text,encoding='utf8')
    print('MATCHED_LORA_SOURCE_PREPARED')

if __name__=='__main__':main()
