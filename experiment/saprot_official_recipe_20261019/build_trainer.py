"""Adapt the existing checked trainer, retaining its resume and test-free selection logic."""
from pathlib import Path
import hashlib,json

HERE=Path(__file__).resolve().parent
ROOT=HERE.parent

def main():
    source=ROOT/'saprot_baseline_20261019/train_saprot_lora.py'
    text=source.read_text(encoding='utf8')
    expected='3744c37cd6d2907dd159a19c3b315915a2493f7315014e7e4c70af3c980cdbb5'
    assert hashlib.sha256(source.read_bytes()).hexdigest()==expected
    def change(old,new):
        nonlocal text
        assert text.count(old)==1,(old,text.count(old))
        text=text.replace(old,new)
    start=text.index('class Regressor(');end=text.index('\ndef loader(',start)
    text=text[:start]+'''class Regressor(nn.Module):
    def __init__(self,path,rank):
        super().__init__()
        assert rank==8
        from model import make_model
        self.backbone=make_model()
    def forward(self,ids,mask):
        return self.backbone(input_ids=ids,attention_mask=mask).logits.squeeze(-1).float()
\n'''+text[end:]
    change('ap.add_argument("--smoke",action="store_true")',
           'ap.add_argument("--smoke",action="store_true")\n    ap.add_argument("--input-mode",choices=["aa","pred3di"],required=True)')
    change('ap.add_argument("--lr",type=float,default=1e-4);ap.add_argument("--rank",type=int,default=16)',
           'ap.add_argument("--lr",type=float,default=1e-4);ap.add_argument("--rank",type=int,default=8)')
    change('f"saprot650_pred3di_lora_seed{a.seed}"','f"saprot650_official_{a.input_mode}_lora_seed{a.seed}"')
    start=text.index('    cache=root/"artifacts/embeddings"');end=text.index('    tr=loader(',start)
    text=text[:start]+'''    from model import token_cache
    import hashlib
    spec=json.loads((HERE/"PROTOCOL.json").read_text())
    audit=json.loads((HERE/"INPUT_AUDIT.json").read_text())
    assert audit['status']=='PASS'
    protocol_hash=hashlib.sha256((HERE/"PROTOCOL.json").read_bytes()).hexdigest()
    assert audit['protocol_sha256']==protocol_hash
    assert a.rank==spec['lora']['rank'] and a.lr==spec['training']['lr']
    assert a.batch_size*a.accumulation==spec['training']['effective_batch']
    if not a.smoke:assert a.epochs==spec['training']['max_epochs'] and a.patience==spec['training']['patience']
    for filename,digest in spec['data_hashes'].items():
        assert hashlib.sha256((root/'data'/filename).read_bytes()).hexdigest()==digest,filename
    tok=token_cache(a.input_mode)
'''+text[end:]
    change('"method":"Native SaProt-650M with predicted 3Di + supervised LoRA",',
           '"method":"Official-style native SaProt CLS regression, trained only on project labels",')
    change('"input_features":"native 221 AA+3Di tokens; no GLOM mutation or local branches",',
           '"input_features":spec["input_modes"][a.input_mode],')
    change('"protocol_sha256":state["protocol_sha256"],"model_revision":spec["model_revision"],',
           '"protocol_sha256":protocol_hash,"model_revision":spec["base_revision"],')
    change('"selection":"validation Spearman","loss":"standardized Huber","amp":"bf16",',
           '"selection":"minimum validation MSE","loss":"raw-label MSE","amp":"bf16",')
    change('"training_test_labels_read":False,"checkpoint_origin":"public pretrained, no GFP labels"',
           '"test_labels_used_for_training_or_selection":False,"checkpoint_origin":"general pretrained only, no external task adapters"')
    change('lr=a.lr,weight_decay=.01)','lr=a.lr,weight_decay=.01,betas=(.9,.98))')
    change('ym=float(frames["train"].brightness.mean());ys=float(frames["train"].brightness.std(ddof=0)+1e-8)',
           'ym=0.;ys=1.  # Official task recipe: MSE on original log-brightness labels.')
    change('loss=nn.functional.huber_loss(z.float(),(y.cuda(non_blocking=True)-ym)/ys)',
           'loss=nn.functional.mse_loss(z.float(),y.cuda(non_blocking=True))')
    change('"train_huber":total/count','"train_mse":total/count')
    change('if metrics["spearman"]>best+1e-6:\n            best=metrics["spearman"];bad=0',
           'if -(metrics["rmse"]**2)>best+1e-6:\n            best=-(metrics["rmse"]**2);bad=0')
    change('"best_validation_spearman":best','"best_validation_mse":-best')
    text=text.replace('"""Native SaProt adaptation; same optimization and head as the frozen ESM LoRA protocol.\nGenerated by build_matched_lora.py; no outcome-driven hyperparameter changes.\n"""',
          '"""Official-style SaProt CLS/LoRA recipe; project labels only; no task checkpoint transfer."""')
    compile(text,'train_official_recipe.py','exec')
    (HERE/'train_official_recipe.py').write_text(text,encoding='utf8')
    (HERE/'TRAINER_DERIVATION.json').write_text(json.dumps({'original':str(source.relative_to(ROOT)),
          'original_sha256':expected,'new_sha256':hashlib.sha256(text.encode()).hexdigest(),
          'changes':['native CLS classifier','new rank-8 q/k/v/attention-output/feedforward LoRA',
                     'AA-only and predicted-3Di inputs','raw-label MSE','AdamW betas .9/.98',
                     'validation MSE selection','same 25-epoch cap, patience 6 and effective batch64'],
          'external_task_weights_used':False},indent=2)+'\n')
    print('OFFICIAL_RECIPE_TRAINER_GENERATED')

if __name__=='__main__':main()
